depends_on: str | Sequence[str] | None = None

CREATED_AT_TABLES = ("users", "rubik_faces", "rubik_states", "histories")


def _server_offset_seconds() -> int:
    connection = op.get_bind()
    return int(
        connection.scalar(
            sa.text("SELECT TIMESTAMPDIFF(SECOND, UTC_TIMESTAMP(), NOW())")
        ) or 0
    )


def upgrade() -> None:
    connection = op.get_bind()
    if connection.dialect.name not in {"mysql", "mariadb"}:
        return
    offset = _server_offset_seconds()
    if offset == 0:
        return
    for table in CREATED_AT_TABLES:
        connection.execute(
            sa.text(
                f"UPDATE {table} "
                "SET created_at = TIMESTAMPADD(SECOND, :delta, created_at)"
            ),
            {"delta": -offset},
        )


