"""Normalize pre-UTC-session server-generated timestamps.

Existing MySQL/MariaDB connections used the server's local timezone for NOW().
Only columns generated by the database are adjusted; client-supplied UTC times
and token expirations are deliberately untouched.

Revision ID: 0004_utc_created_at
Revises: 0003_kociemba_only
"""

